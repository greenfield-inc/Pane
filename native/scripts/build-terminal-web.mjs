// Bundles terminal-web/page.ts (xterm and its CSS) into one HTML string that the
// terminal WebView loads with no network access. Run after changing the page or
// upgrading xterm: `pnpm build:terminal-web`.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

import { build } from 'esbuild';

const root = fileURLToPath(new URL('..', import.meta.url));
const require = createRequire(import.meta.url);

const { outputFiles } = await build({
  entryPoints: [`${root}terminal-web/page.ts`],
  bundle: true,
  minify: true,
  format: 'iife',
  target: ['safari16', 'chrome110'],
  write: false,
  legalComments: 'none',
});
const script = outputFiles[0].text;
const css = readFileSync(require.resolve('@xterm/xterm/css/xterm.css'), 'utf8');

const html = `<!doctype html>
<html>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no">
<style>${css}
html, body { margin: 0; height: 100%; overflow: hidden; -webkit-user-select: none; user-select: none; -webkit-text-size-adjust: 100%; }
#terminal { position: absolute; inset: 4px 6px; }
.xterm-viewport { overflow: hidden !important; }
</style>
</head>
<body>
<div id="terminal"></div>
<script>${script.replaceAll('</script', '<\\/script')}</script>
</body>
</html>
`;

writeFileSync(
  `${root}src/features/terminal/terminalHtml.generated.ts`,
  `// Generated by scripts/build-terminal-web.mjs from terminal-web/page.ts. Do not edit.\n` +
    `// eslint-disable-next-line\nexport const terminalHtml = ${JSON.stringify(html)};\n`,
);
console.log(`terminalHtml.generated.ts: ${(html.length / 1024).toFixed(0)} KB`);
